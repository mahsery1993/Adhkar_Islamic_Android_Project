    fun getRandomDhikr(
        includeMorning: Boolean,
        includeEvening: Boolean,
        includeJawami: Boolean,
        includePrayer: Boolean = true,
        includeSleep: Boolean = true,
        includeRuqyah: Boolean = true
    ): DhikrItem {
        val allowed = mutableListOf<String>()
        if (includeMorning) allowed.add("morning")
        if (includeEvening) allowed.add("evening")
        if (includeJawami) allowed.add("jawami")
        if (includePrayer) allowed.add("prayer")
        if (includeSleep) allowed.add("sleep")
        if (includeRuqyah) allowed.add("ruqyah")
        if (allowed.isEmpty()) allowed.add("jawami")

        val filtered = allAdhkar.filter { allowed.contains(it.category) }
        return filtered.randomOrNull() ?: allAdhkar.first()
    }
